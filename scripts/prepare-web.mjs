// Copies www/ into dist/ and bundles fonts (from @fontsource packages) so the app works fully offline.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const www = path.join(root, 'www');
const dist = path.join(root, 'dist');

const FONT_PACKAGES = [
  'vazirmatn', 'lalezar', 'amiri', 'aref-ruqaa', 'reem-kufi', 'noto-naskh-arabic', 'noto-nastaliq-urdu',
  'playfair-display', 'cormorant-garamond', 'great-vibes', 'dancing-script', 'cinzel', 'montserrat',
  'pacifico', 'comfortaa',
];
const WEIGHTS = ['400', '700'];

fs.rmSync(dist, { recursive: true, force: true });
fs.cpSync(www, dist, { recursive: true });

const fontsOut = path.join(dist, 'fonts');
fs.mkdirSync(fontsOut, { recursive: true });
let css = '/* generated by scripts/prepare-web.mjs */\n';
const bundled = [];
for (const pkg of FONT_PACKAGES) {
  const src = path.join(root, 'node_modules', '@fontsource', pkg);
  if (!fs.existsSync(src)) { console.warn('font package missing, skipped:', pkg); continue; }
  const out = path.join(fontsOut, pkg);
  fs.mkdirSync(path.join(out, 'files'), { recursive: true });
  let got = 0;
  for (const w of WEIGHTS) {
    const cssFile = path.join(src, `${w}.css`);
    if (!fs.existsSync(cssFile)) continue;
    let text = fs.readFileSync(cssFile, 'utf8');
    // keep only woff2 sources
    text = text.replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '');
    const used = [...text.matchAll(/url\(\.\/files\/([^)]+\.woff2)\)/g)].map((m) => m[1]);
    for (const f of used) {
      const from = path.join(src, 'files', f);
      if (fs.existsSync(from)) fs.copyFileSync(from, path.join(out, 'files', f));
    }
    fs.writeFileSync(path.join(out, `${w}.css`), text);
    css += `@import url('../fonts/${pkg}/${w}.css');\n`;
    got++;
  }
  if (got) bundled.push(pkg);
}
fs.mkdirSync(path.join(dist, 'css'), { recursive: true });
fs.writeFileSync(path.join(dist, 'css', 'fonts.css'), css);
fs.writeFileSync(path.join(dist, 'fonts', 'bundled.json'), JSON.stringify(bundled));
console.log(`dist ready. fonts bundled: ${bundled.length}/${FONT_PACKAGES.length}`);
